#!/usr/bin/env python3
"""Generate crates/sim/src/trig_table.rs.

The simulation may not use floating point, and even if it could, libm's sin()
is not guaranteed bit-identical across platforms. So the table is generated
once, here, and committed. Re-run only if you change the table shape.

Quarter-wave table: entry i is round(sin(i / 256 * pi/2) * 65536), for
i in 0..=256. The full circle is reconstructed by symmetry in angle.rs.
"""
import math, pathlib

N = 256
entries = [round(math.sin(i / N * math.pi / 2) * 65536) for i in range(N + 1)]
assert entries[0] == 0 and entries[N] == 65536

out = pathlib.Path(__file__).resolve().parents[2] / "crates/sim/src/trig_table.rs"
lines = [
    "//! Generated by tools/gen/gen_trig_table.py. Do not edit by hand.",
    "//!",
    "//! Quarter-wave sine table in Q16.16: `SIN_QUARTER[i] = sin(i/256 * pi/2)`.",
    "",
    "/// Number of table steps in a quarter turn.",
    f"pub const QUARTER_STEPS: u32 = {N};",
    "",
    f"pub const SIN_QUARTER: [i32; {N + 1}] = [",
]
for i in range(0, N + 1, 8):
    chunk = entries[i:i + 8]
    lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
lines.append("];")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out} ({N + 1} entries)")
